"""The Market Entry List: the pairs the bot is actually allowed to trade.

Screening decides which pairs are statistically sound; this list decides which
of them the client wants live. Per the client, "all pairs for trading has to
be from the Market Entry List", and it is maintained by hand from the
dashboard rather than regenerated by the screen -- so a pair dropping out of a
day's screen does not silently remove it, and a newly qualifying pair does not
silently start trading.

Pairs are stored and compared unordered: GOOG/META and META/GOOG are the same
pair, and the screen's column order is an implementation detail of whichever
symbol sorted first.
"""
import json
import logging
import os
from pathlib import Path

logger = logging.getLogger("pairs_bot.market_entry_list")

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
MARKET_ENTRY_LIST_PATH = str(DATA_DIR / "market_entry_list.json")


def pair_key(symbol_a: str, symbol_b: str) -> tuple[str, str]:
    """Order-independent identity for a pair."""
    return tuple(sorted((symbol_a.strip().upper(), symbol_b.strip().upper())))


def load_market_entry_list(path: str = MARKET_ENTRY_LIST_PATH) -> set[tuple[str, str]] | None:
    """The allowed pairs, or None if no list has been configured.

    None and empty are deliberately different. None means the file is absent,
    i.e. nobody has set a list up, and the caller falls back to trading
    everything that qualified. An empty list is a real instruction -- someone
    removed every pair from the dashboard -- and means trade nothing.
    """
    if not os.path.exists(path):
        return None
    try:
        with open(path) as f:
            raw = json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        # Never fail open on a corrupt file: silently trading the full
        # qualified list when the client believes only four pairs are live is
        # worse than not trading.
        logger.error(f"market entry list at {path} is unreadable ({e}) -- trading nothing this session")
        return set()
    return {pair_key(*p) for p in raw.get("pairs", [])}


def save_market_entry_list(pairs, path: str = MARKET_ENTRY_LIST_PATH) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    ordered = sorted({pair_key(a, b) for a, b in pairs})
    tmp = f"{path}.tmp"
    with open(tmp, "w") as f:
        json.dump({"pairs": [list(p) for p in ordered]}, f, indent=2)
    os.replace(tmp, path)  # atomic, so a dashboard edit can't leave a half-written file


def add_pair(symbol_a: str, symbol_b: str, path: str = MARKET_ENTRY_LIST_PATH) -> None:
    current = load_market_entry_list(path) or set()
    save_market_entry_list(current | {pair_key(symbol_a, symbol_b)}, path)


def remove_pair(symbol_a: str, symbol_b: str, path: str = MARKET_ENTRY_LIST_PATH) -> None:
    current = load_market_entry_list(path)
    if current is None:
        return
    save_market_entry_list(current - {pair_key(symbol_a, symbol_b)}, path)


def filter_to_market_entry_list(contexts, path: str = MARKET_ENTRY_LIST_PATH):
    """Narrows the screened pairs down to the ones cleared for trading."""
    allowed = load_market_entry_list(path)
    if allowed is None:
        logger.warning("no market entry list configured -- trading all %d qualified pairs", len(contexts))
        return contexts

    kept = [c for c in contexts if pair_key(c.symbol_a, c.symbol_b) in allowed]
    dropped = [f"{c.symbol_a}/{c.symbol_b}" for c in contexts
               if pair_key(c.symbol_a, c.symbol_b) not in allowed]
    if dropped:
        logger.info("not on the market entry list, will not be traded: %s", ", ".join(dropped))

    # A pair on the list that did not qualify today is worth saying out loud:
    # it stays on the list, but it is not trading and the client should know
    # which of their chosen pairs is sitting idle.
    screened = {pair_key(c.symbol_a, c.symbol_b) for c in contexts}
    missing = sorted(allowed - screened)
    if missing:
        logger.warning("on the market entry list but did not qualify in screening: %s",
                       ", ".join(f"{a}/{b}" for a, b in missing))
    logger.info("market entry list: trading %d pair(s)", len(kept))
    return kept
